export const getCarsByCategory = (slug) =>
  cars.filter((c) => c.category === slug);

export const getCarBySlug = (slug) =>
  cars.find((c) => c.slug === slug);

export const getCategoryBySlug = (slug) =>
  categories.find((c) => c.slug === slug);

export const getRelatedCars = (car, count = 3) =>
  cars
    .filter(
      (c) =>
        c.category === car.category &&
        c.slug !== car.slug
    )
    .slice(0, count);